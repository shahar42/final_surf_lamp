"""
Regenerate fixtures/mac_vectors.txt: the shared MAC -> Arduino ID cases run by
BOTH sides of the fold.

The server folds a pasted MAC into an Arduino ID (web utils/device_id.py);
the firmware folds its eFuse MAC into the same ID at boot (Config.h
getArduinoId). If they disagree, a user registers an ID no lamp ever polls
with. This file is the single list of cases; the Makefile feeds each row to
the native test_arduino_id binary, and tests/unit/web/test_device_id.py
checks the committed file against the Python fold.

Column 3 is the uint64 the firmware's ESP.getEfuseMac() returns for that MAC:
esp_efuse_mac_get_default fills a 6-byte array (octet 0 first), which is then
read as a little-endian uint64, so octet 0 lands in the LOW byte.

    esurf/bin/python tests/unit/firmware/gen_mac_vectors.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, os.path.join(ROOT, "web_and_database"))

# Printed MACs worth pinning: ordinary, all-ones (max ID), zero NIC bytes
# (the reserved-0 bump), and a low-bit case.
MACS = [
    "00:11:22:33:44:55",
    "A4:CF:12:34:56:78",
    "FF:FF:FF:FF:FF:FF",
    "AA:BB:CC:00:00:00",
    "AA:BB:CC:00:00:01",
]


def efuse_u64(mac: str) -> int:
    """The uint64 ESP.getEfuseMac() returns for this printed MAC."""
    octets = [int(p, 16) for p in mac.split(":")]
    return sum(octet << (8 * i) for i, octet in enumerate(octets))


def rows():
    from utils.device_id import arduino_id_from_mac
    return [(mac, f"0x{efuse_u64(mac):012X}", arduino_id_from_mac(mac)) for mac in MACS]


def lines():
    out = ["# generated by gen_mac_vectors.py -- printed_mac efuse_u64 expected_arduino_id"]
    out += [f"{mac} {u64} {device_id}" for mac, u64, device_id in rows()]
    return out


def main():
    out_dir = os.path.join(HERE, "fixtures")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "mac_vectors.txt")
    with open(path, "w") as f:
        f.write("\n".join(lines()) + "\n")
    print(f"wrote {path} ({len(MACS)} vectors)")


if __name__ == "__main__":
    main()
